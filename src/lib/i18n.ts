export function translateApi(message: string, locale: Locale): string {
  if (locale === "en") return message;
  const status = /^Source unavailable \(HTTP (\d+)\)/.exec(message);
  return (
    apiMessages[message] ||
    (status
      ? `数据源暂时不可用（HTTP ${status[1]}），请重试或切换来源。`
      : message)
  );
}

